"""XNYS exchange calendar (rule MD-005, DF-011).

Reads the same session table as the Go services (``xnys_sessions.csv``, generated by
``scripts/gen_calendar.py`` from exchange_calendars). All times are UTC.
"""

from __future__ import annotations

import bisect
from dataclasses import dataclass
from datetime import UTC, date, datetime, timedelta
from functools import lru_cache
from importlib import resources

TIMEFRAMES: dict[str, timedelta] = {
    "1m": timedelta(minutes=1),
    "5m": timedelta(minutes=5),
    "15m": timedelta(minutes=15),
    "30m": timedelta(minutes=30),
    "1h": timedelta(hours=1),
    "1d": timedelta(days=1),
}


@dataclass(frozen=True, slots=True)
class Session:
    """One trading day; all datetimes are timezone-aware UTC."""

    date: date
    pre_open: datetime
    open: datetime
    close: datetime
    post_close: datetime
    early_close: bool

    def bar_opens(self, timeframe: str, extended: bool = False) -> list[datetime]:
        """Expected bar opens, aligned to the session start, never crossing the session end (MD-004)."""
        if timeframe == "1d":
            return [self.open]
        step = TIMEFRAMES[timeframe]
        start, end = (self.pre_open, self.post_close) if extended else (self.open, self.close)
        out: list[datetime] = []
        t = start
        while t < end:
            out.append(t)
            t += step
        return out

    def bar_close(self, bar_open: datetime, timeframe: str) -> datetime:
        """Close of the bar opened at ``bar_open``, truncated at the session part's end."""
        if timeframe == "1d":
            return self.close
        end = bar_open + TIMEFRAMES[timeframe]
        if bar_open < self.open < end:
            return self.open
        if bar_open < self.close < end:
            return self.close
        return min(end, self.post_close)


def _ts(s: str) -> datetime:
    return datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=UTC)


class Calendar:
    """Immutable session table with lookups."""

    def __init__(self, sessions: list[Session]) -> None:
        self._sessions = sessions
        self._opens = [s.open for s in sessions]
        self._post = [s.post_close for s in sessions]
        self._closes = [s.close for s in sessions]
        self._by_date = {s.date: s for s in sessions}

    @classmethod
    def from_csv(cls, text: str) -> Calendar:
        sessions = []
        for line in text.strip().splitlines()[1:]:
            d, pre, op, cl, post, early = line.split(",")
            sessions.append(Session(date.fromisoformat(d), _ts(pre), _ts(op), _ts(cl), _ts(post), early == "1"))
        return cls(sessions)

    def session(self, d: date) -> Session | None:
        return self._by_date.get(d)

    def sessions(self, start: datetime, end: datetime) -> list[Session]:
        """Sessions whose regular open is in ``[start, end)``."""
        i = bisect.bisect_left(self._opens, start)
        j = bisect.bisect_left(self._opens, end)
        return self._sessions[i:j]

    def session_at(self, ts: datetime) -> tuple[Session | None, str]:
        """The session containing ``ts`` (extended hours included) and the part: pre/regular/post/closed."""
        i = bisect.bisect_right(self._post, ts)
        if i < len(self._sessions) and self._sessions[i].pre_open <= ts:
            s = self._sessions[i]
            part = "pre" if ts < s.open else "regular" if ts < s.close else "post"
            return s, part
        return None, "closed"

    def is_open(self, ts: datetime) -> bool:
        return self.session_at(ts)[1] == "regular"

    def next_open(self, ts: datetime) -> datetime | None:
        i = bisect.bisect_right(self._opens, ts)
        return self._opens[i] if i < len(self._opens) else None

    def previous_session(self, ts: datetime) -> Session | None:
        """Last session whose regular close is at or before ``ts``."""
        i = bisect.bisect_right(self._closes, ts)
        return self._sessions[i - 1] if i > 0 else None

    def bar_close_times(self, timeframe: str, d: date, extended: bool = False) -> list[datetime]:
        s = self.session(d)
        if s is None:
            return []
        return [s.bar_close(o, timeframe) for o in s.bar_opens(timeframe, extended)]


@lru_cache(maxsize=1)
def xnys() -> Calendar:
    """The shared NYSE calendar."""
    text = resources.files("tbcore.data").joinpath("xnys_sessions.csv").read_text()
    return Calendar.from_csv(text)
